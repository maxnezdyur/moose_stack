**********************************************************************
**  STAND-IN UMAT FOR THE TWO-BLOCK THERMOMECHANICAL DEMO.
**  REPLACE WITH THE GROUP'S OWN UMAT; THE INTERFACE IS THE SAME.
**
**  LINEAR VISCO-ELASTIC (MAXWELL) SOLID WITH THERMAL EXPANSION.
**  STATE VARIABLE Z = STATEV(1) IS THE ACCUMULATED EQUIVALENT
**  VISCOUS STRAIN. Z HARDENS THE VISCOSITY: ETA = ETA0*(1+CZ*Z).
**
**  PROPS(1) E      YOUNG'S MODULUS [PA]
**  PROPS(2) NU     POISSON'S RATIO [-]
**  PROPS(3) ALPHA  COEFFICIENT OF THERMAL EXPANSION [1/K]
**  PROPS(4) ETA0   SHEAR VISCOSITY AT Z = 0 [PA S]
**  PROPS(5) CZ     HARDENING OF THE VISCOSITY WITH Z [-]
**********************************************************************
      SUBROUTINE UMAT(STRESS,STATEV,DDSDDE,SSE,SPD,SCD,
     1     RPL,DDSDDT,DRPLDE,DRPLDT,
     2     STRAN,DSTRAN,TIME,DTIME,TEMP,DTEMP,PREDEF,DPRED,CMNAME,
     3     NDI,NSHR,NTENS,NSTATV,PROPS,NPROPS,COORDS,DROT,PNEWDT,
     4     CELENT,DFGRD0,DFGRD1,NOEL,NPT,LAYER,KSPT,KSTEP,KINC)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      CHARACTER*80 CMNAME
      DIMENSION STRESS(NTENS),STATEV(NSTATV),DDSDDE(NTENS,NTENS),
     1     DDSDDT(NTENS),DRPLDE(NTENS),STRAN(NTENS),DSTRAN(NTENS),
     2     TIME(2),PREDEF(1),DPRED(1),PROPS(NPROPS),COORDS(3),
     3     DROT(3,3),DFGRD0(3,3),DFGRD1(3,3)
      DIMENSION DEPS(6),SDEV(6)
      PARAMETER(ZERO=0.D0,ONE=1.D0,TWO=2.D0,THREE=3.D0)

      E=PROPS(1)
      ENU=PROPS(2)
      ALPHA=PROPS(3)
      ETA0=PROPS(4)
      CZ=PROPS(5)

      G=E/(TWO*(ONE+ENU))
      BK=E/(THREE*(ONE-TWO*ENU))
      ETA=ETA0*(ONE+CZ*STATEV(1))
      FAC=ONE/(ONE+G*DTIME/ETA)

C     MECHANICAL STRAIN INCREMENT, TENSOR SHEAR COMPONENTS
      DO I=1,NDI
         DEPS(I)=DSTRAN(I)-ALPHA*DTEMP
      END DO
      DO I=NDI+1,NTENS
         DEPS(I)=DSTRAN(I)/TWO
      END DO
      DVOL=DEPS(1)+DEPS(2)+DEPS(3)

C     VOLUMETRIC PART IS ELASTIC
      PO=(STRESS(1)+STRESS(2)+STRESS(3))/THREE
      PN=PO+BK*DVOL

C     DEVIATORIC PART RELAXES (BACKWARD EULER MAXWELL UPDATE)
      DO I=1,NDI
         SDEV(I)=FAC*(STRESS(I)-PO+TWO*G*(DEPS(I)-DVOL/THREE))
      END DO
      DO I=NDI+1,NTENS
         SDEV(I)=FAC*(STRESS(I)+TWO*G*DEPS(I))
      END DO

      DO I=1,NDI
         STRESS(I)=SDEV(I)+PN
      END DO
      DO I=NDI+1,NTENS
         STRESS(I)=SDEV(I)
      END DO

C     ACCUMULATED EQUIVALENT VISCOUS STRAIN
      SUM=ZERO
      DO I=1,NDI
         SUM=SUM+SDEV(I)**2
      END DO
      DO I=NDI+1,NTENS
         SUM=SUM+TWO*SDEV(I)**2
      END DO
      DZ=SQRT(TWO/THREE*SUM)*DTIME/(TWO*ETA)
      STATEV(1)=STATEV(1)+DZ

C     CONSISTENT TANGENT AT FIXED Z (ENGINEERING SHEAR STRAINS)
      DO I=1,NTENS
         DO J=1,NTENS
            DDSDDE(I,J)=ZERO
         END DO
      END DO
      DO I=1,NDI
         DO J=1,NDI
            DDSDDE(I,J)=BK-TWO*G*FAC/THREE
         END DO
         DDSDDE(I,I)=DDSDDE(I,I)+TWO*G*FAC
         DDSDDT(I)=-THREE*BK*ALPHA
      END DO
      DO I=NDI+1,NTENS
         DDSDDE(I,I)=G*FAC
         DDSDDT(I)=ZERO
      END DO

      RPL=ZERO
      RETURN
      END
